-- Skema lengkap Sahabat Tani untuk Postgres (Supabase), setara migrasi SQLite 001–009.
-- Tanggal disimpan sebagai TEXT 'YYYY-MM-DD HH:MM:SS' (UTC) seperti di SQLite, agar kode & format tampilan tetap sama.
-- Nilai ya/tidak disimpan sebagai INTEGER 0/1 seperti di SQLite.

-- ---------- Fungsi kompatibilitas SQLite ----------
-- datetime('now'), datetime('now', '+30 minutes'), datetime('now', '-7 days'), datetime(kolom)
CREATE OR REPLACE FUNCTION datetime(t text, modifier text DEFAULT NULL) RETURNS text
LANGUAGE sql STABLE AS $$
  SELECT to_char(
    (CASE WHEN t = 'now' THEN now() AT TIME ZONE 'utc' ELSE t::timestamp END) + COALESCE(modifier::interval, interval '0'),
    'YYYY-MM-DD HH24:MI:SS')
$$;
-- json_extract(teks_json, '$.kunci') → teks
CREATE OR REPLACE FUNCTION json_extract(doc text, path text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT (doc::jsonb) #>> string_to_array(regexp_replace(path, '^\$\.?', ''), '.')
$$;

-- ---------- Tabel ----------
CREATE TABLE users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone         text UNIQUE,
  email         text UNIQUE,
  password_hash text,
  role          text NOT NULL DEFAULT 'farmer' CHECK (role IN ('farmer', 'admin')),
  is_active     integer NOT NULL DEFAULT 1,
  is_demo       integer NOT NULL DEFAULT 0,
  created_at    text NOT NULL DEFAULT datetime('now'),
  last_login_at text,
  CHECK (phone IS NOT NULL OR email IS NOT NULL)
);

CREATE TABLE password_resets (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expires_at text NOT NULL,
  used_at    text,
  created_at text NOT NULL DEFAULT datetime('now')
);

